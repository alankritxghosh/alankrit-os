def beliefs(model):
    src = sorted(_of(model, "belief", prefix="icarus:"), key=lambda r: int(r["local_id"][1:]))
    hist = _of(model, "belief", prefix="global:")
    from collections import Counter
    cnt = Counter(r["global_status"] for r in src + hist)
    L = ["Statuses: CURRENT · PERSISTENT (spans project generations) · EVOLVING · HISTORICAL · REJECTED · EXPLORATORY · UNCERTAIN. "
         "Exploratory thinking is never promoted. 'first/last observed' are dates of evidence, not of the belief's birth.", "",
         "Status counts: " + ", ".join(f"{k} {v}" for k, v in sorted(cnt.items())), ""]
    domain = None
    for r in src:
        if r["domain"] != domain:
            domain = r["domain"]
            L += [f"## {domain}", ""]
        L += [f"### [{r['id']}] {r['statement']}", "",
              f"- **Status:** {r['global_status']} · **Confidence:** {r['confidence']} · **Kind:** {r['kind']} · **Class:** {r['classification']}",
              f"- **First / last observed:** {r['first_observed']} → {r['last_observed']}",
              f"- **Projects:** {', '.join(r['observed_in_projects'])}",
              f"- **Supporting evidence (source):** {r['text']}",
              f"- **Contradicting evidence:** {'; '.join(r['contradicting_evidence']) or 'none recorded'}",
              f"- **Associated decisions:** {', '.join(f'[{d}]' for d in r['associated_decisions']) or '—'}"]
        if r.get("compiler_note"):
            L.append(f"- **Compiler note:** {r['compiler_note']}")
        L += [f"- **Source:** {_src(r)}", ""]
    L += ["## Historical and rejected beliefs (reconstructed from decisions and reversals)", "",
          "These were not listed as beliefs by the extractor; they are inferred from decisions that were later reversed. Basis: RECONSTRUCTED, confidence MEDIUM.", "",
          "| ID | belief | status | held | evidence | what replaced it |", "|---|---|---|---|---|---|"]
    for r in sorted(hist, key=lambda r: r["id"]):
        L.append(f"| [{r['id']}] | {r['statement']} | {r['global_status']} | {r['first_observed']} → {r['last_observed']} | "
                 f"{', '.join(f'[{x}]' for x in r['refs'])} | {r['compiler_note']} |")
    doc("04_GLOBAL_BELIEF_SYSTEM.md", "04 — Global Belief System", "\n".join(L))


