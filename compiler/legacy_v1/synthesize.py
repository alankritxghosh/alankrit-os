def transferable(model):
    buckets = {}
    for r in _of(model, "belief", prefix="icarus:"):
        buckets.setdefault(r["classification"], []).append((r["id"], r["statement"], f"belief, {r['global_status']}"))
    for r in _of(model, "belief", prefix="global:"):
        buckets.setdefault("PROJECT-SPECIFIC", []).append((r["id"], r["statement"], f"reconstructed belief, {r['global_status']}"))
    for r in _of(model, "decision"):
        buckets.setdefault("PROJECT-SPECIFIC", []).append((r["id"], r["title"], "decision"))
    head_map = {"Likely general to Alankrit": "PERSONAL PREFERENCE", "Reusable technical knowledge": "TECHNICAL KNOWLEDGE",
                "Reusable product lessons": "PRODUCT KNOWLEDGE", "Reusable GTM lessons": "BUSINESS KNOWLEDGE",
                "Failed approaches worth avoiding": "TECHNICAL KNOWLEDGE", "Decisions that constrain future projects (if continued)": "PROJECT-SPECIFIC",
                "Project-specific (do not generalize)": "PROJECT-SPECIFIC"}
    for r in _of(model, "transferable_insight"):
        cls = head_map.get(r["heading"], "UNCERTAIN")
        if r["text"].startswith(("Templated cold email",)):
            cls = "BUSINESS KNOWLEDGE"
        if r["text"].startswith(("Strong visual taste", "Distribution is his recurring")):
            cls = "UNCERTAIN"
        buckets.setdefault(cls, []).append((r["id"], r["text"], f"extractor: {r['heading']}"))
    for r in _of(model, "reasoning_pattern"):
        buckets.setdefault("STRATEGIC PRINCIPLE" if r["local_id"] in {"R2", "R3", "R4", "R8", "R9", "R10", "R13", "R16"} else "UNCERTAIN", []).append(
            (r["id"], r["pattern"], "reasoning pattern (single project)"))
    order = ["PERSONAL PREFERENCE", "STRATEGIC PRINCIPLE", "TECHNICAL KNOWLEDGE", "PRODUCT KNOWLEDGE", "BUSINESS KNOWLEDGE", "UNCERTAIN", "PROJECT-SPECIFIC"]
    desc = {"PERSONAL PREFERENCE": "Potentially stable preference. Evidence repeats across surfaces (code, content, outreach, agent instructions) but within one project.",
            "STRATEGIC PRINCIPLE": "Potentially general principle. Stated as general by him; tested in one project.",
            "TECHNICAL KNOWLEDGE": "Reusable technical knowledge, independent of who holds it.",
            "PRODUCT KNOWLEDGE": "Reusable product knowledge.", "BUSINESS KNOWLEDGE": "Reusable business/GTM knowledge (mostly small-n).",
            "UNCERTAIN": "Insufficient evidence to classify, or in tension with other evidence.",
            "PROJECT-SPECIFIC": "Only relevant to Icarus. Never convert these into personality traits."}
    L = ["Rule: a project decision is never promoted to a personal trait. Only items with evidence on several surfaces "
         "(engineering, content, outreach, job search, agent instructions) or across project generations are labelled PERSONAL PREFERENCE.", "",
         "Counts: " + ", ".join(f"{k} {len(buckets.get(k, []))}" for k in order), ""]
    for k in order:
        L += [f"## {k}", "", desc[k], "", "| ref | insight | basis |", "|---|---|---|"]
        L += [f"| [{i}] | {_c(t)} | {b} |" for i, t, b in buckets.get(k, [])]
        L.append("")
    L += ["## Classification cautions", "",
          "- 'Address him as Alankrit' and 'no em-dashes' come from the Icarus CLAUDE.md and project memories. The extractor rates them general (HIGH). "
          "The em-dash rule spans content, outreach and docs; the address rule is evidenced only in one CLAUDE.md. Treat the address rule as UNCERTAIN outside Icarus.",
          "- 'Cash-constrained' is a 2026 constraint, not a preference [icarus:X11L8].",
          "- 'The bottleneck is distribution' [icarus:B21] is a diagnosis of Icarus, not a trait."]
    model["transferable_buckets"] = {k: len(v) for k, v in buckets.items()}
    doc("14_TRANSFERABLE_CONTEXT.md", "14 — Transferable Context", "\n".join(L))


