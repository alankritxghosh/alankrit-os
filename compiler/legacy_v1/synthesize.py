def voice_examples(model):
    vs = sorted(_of(model, "voice_example"), key=lambda r: r["id"])
    cats = ["argument", "explanation", "reflection", "technical reasoning", "disagreement", "short-form", "long-form", "humor", "directness", "counter-example"]
    prov = {"POSTED": "posted publicly by him (X/LinkedIn), as quoted by the extractor",
            "HIS_FEEDBACK": "his own words in feedback to agents (memories/vault)",
            "HIS_RULE": "a rule or template he specified", "HIS_FRAMING": "his framing, recorded in vault/plans",
            "DOC_PHRASE": "phrasing in his vault/repo docs; authorship may be shared with AI agents working under his direction",
            "AI_HOUSE_STYLE": "written by AI agents under his direction; NOT his direct voice",
            "REJECTED": "a line he rejected as not his voice"}
    idx = ["# Voice Examples", "", HDR.format(date=COMPILE_DATE),
           "Structured references, not copies of source files. Each excerpt was verified to occur verbatim in the cited source file "
           "(`verified` in `memory/voice_examples.jsonl`).", "", "## Provenance classes", ""]
    idx += [f"- **{k}**: {v}" for k, v in prov.items()]
    idx += ["", "## By category", ""]
    for c in cats:
        items = [v for v in vs if c in v["categories"]]
        idx.append(f"- [{c}]({c.replace(' ', '_')}.md): {len(items)}" + (" — **no genuine evidence in corpus**" if not items else ""))
        body = [f"# Voice examples: {c}", "", HDR.format(date=COMPILE_DATE)]
        if not items:
            body.append({"long-form": "No long-form text by Alankrit is in the corpus. Substack exists (every title opens with 'Why'; section headers are "
                                      "declarative thesis sentences) but was not read by the extractor. Do not synthesize long-form voice from short lines.",
                         "explanation": "No examples."}.get(c, "No examples."))
        for v in items:
            s = v["source"]
            body += [f"## [{v['id']}]", "", f"> {v['excerpt']}", "",
                     f"- Source: project `icarus`, file `{s['file']}`, line {s['line']} · verified: {v['verified']}",
                     f"- Date: not recorded with the excerpt (corpus evidence spans 2026-06-27 → 2026-09-10)",
                     f"- Provenance: **{v['provenance']}** ({prov[v['provenance']]})",
                     f"- Categories: {', '.join(v['categories'])}", f"- Why it represents his voice: {v['why']}", ""]
        if c == "humor":
            body.append("Caveat: humor evidence is thin. The corpus shows flat self-deprecation and a 'slightly wry' commit house style; no jokes.")
        write_text(f"voice_examples/{c.replace(' ', '_')}.md", "\n".join(body) + "\n")
    write_text("voice_examples/README.md", "\n".join(idx) + "\n")


