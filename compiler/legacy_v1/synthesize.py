HDR = ("> Generated by `python compiler/run.py` on {date}. Source corpus is read-only; refs like "
       "`[icarus:D07]` resolve to `memory/*.jsonl` and to file:line in the source. "
       "Narrative synthesis covers the Icarus extraction (incl. JARVIS v0 history); other extracted projects are inventoried and "
       "parsed but not yet reconciled. See `00_SOURCE_INVENTORY.md` and `16_VALIDATION_REPORT.md`.\n")


def _c(text):
    return re.sub(r"\s+", " ", str(text or "")).replace("|", "/").strip()


def _src(r):
    s = r.get("source", {})
    return f"`{s.get('file')}:{s.get('line')}`" if "file" in s else ", ".join(f"[{x}]" for x in s.get("derived_from", []))


def _of(model, *types, prefix=None):
    # narrative/registers render only the overlay-reconciled project plus compiler-level records
    return [r for r in model["records"].values() if r["type"] in types and (prefix is None or r["id"].startswith(prefix))
            and r.get("project") in (C.PROJECT, "global", None)]


def doc(name, title, body):
    write_text(name, f"# {title}\n\n{HDR.format(date=COMPILE_DATE)}\n{body.rstrip()}\n")


